#!/usr/bin/env python3
"""Exact finite checks for the manuscript. Python 3; standard library only.

Run: python3 verify.py
This is mathematical verification of finite instances, not a proof of the
universal theorem. No random samples or floating-point comparisons are used.
"""
from itertools import combinations
from math import comb
from pathlib import Path
import json
import time


def subsets(mask):
    s = mask
    while True:
        yield s
        if s == 0:
            return
        s = (s - 1) & mask


def products(n, weights):
    ans = [1] * (1 << n)
    for s in range(1, 1 << n):
        bit = s & -s
        ans[s] = ans[s ^ bit] * weights[bit.bit_length() - 1]
    return ans


def upmask(n, witnesses):
    return sum(1 << s for s in range(1 << n)
               if any(s & h == h for h in witnesses))


def ranks(n, umask, prod=None):
    result = [0] * (n + 1)
    if prod is None:
        prod = [1] * (1 << n)
    while umask:
        bit = umask & -umask
        s = bit.bit_length() - 1
        result[s.bit_count()] += prod[s]
        umask ^= bit
    return result


def ulc_defects(coeff):
    n = len(coeff) - 1
    return [k * (n-k) * coeff[k]**2
            - (k+1) * (n-k+1) * coeff[k-1] * coeff[k+1]
            for k in range(1, n)]


def variance_check(coeff):
    n = len(coeff) - 1
    z = sum(coeff)
    mean_num = sum(k*a for k,a in enumerate(coeff))
    second_num = sum(k*k*a for k,a in enumerate(coeff))
    return n*z*(second_num-mean_num) <= (n-1)*mean_num**2


def canonical_families(n):
    """All distinct upsets generated by singletons and pairs.

    A canonical specification selects its singleton witnesses; all pair
    witnesses then lie among the remaining vertices. Hence no duplicates.
    The empty upset is included; the full upset is added separately.
    """
    all_bits = (1 << n) - 1
    contains = [upmask(n, [h]) for h in range(1 << n)]
    for loopmask in range(1 << n):
        base = 0
        for i in range(n):
            if loopmask >> i & 1:
                base |= contains[1 << i]
        verts = [i for i in range(n) if not (loopmask >> i & 1)]
        pair_masks = [(1 << i) | (1 << j) for i,j in combinations(verts,2)]
        all_up = [base]
        for pair in pair_masks:
            witness_up = contains[pair]
            all_up += [old | witness_up for old in all_up]
        yield from all_up


def verify_graph_families(max_n=6):
    summary = []
    for n in range(1, max_n+1):
        full = (1 << n)-1
        weight_vectors = [[1]*n, list(range(1,n+1)), [3**i for i in range(n)]]
        prods = [products(n,w) for w in weight_vectors]
        expected = sum(comb(n,l) * 2**comb(n-l,2) for l in range(n+1))
        count = 0
        for umask in canonical_families(n):
            count += 1
            for prod in prods:
                coeff = ranks(n,umask,prod)
                if not (all(d >= 0 for d in ulc_defects(coeff))): raise SystemExit('FAIL: ' + repr((n,umask,coeff)))
                if not (variance_check(coeff)): raise SystemExit('FAIL: ' + repr((n,umask,coeff)))
            double = [s for s in range(1<<n)
                      if (umask>>s)&1 and (umask>>(full^s))&1]
            b = [0]*(n+1)
            c = [0]*(n+1)
            for s in double:
                j=s.bit_count()
                b[j]+=1
                t=s
                while t:
                    bit=t&-t
                    c[j] += 1 - ((umask>>(s^bit))&1)
                    t ^= bit
            if not (b == list(reversed(b))): raise SystemExit('FAIL: ' + repr('line 113'))
            for k in range(1,n+1):
                if not (k*b[k]-(n-k+1)*b[k-1] == c[k]-c[n-k+1]): raise SystemExit('FAIL: ' + repr('line 115'))
            for k in range(1,n//2+1):
                if not (k*b[k] >= (n-k+1)*b[k-1]): raise SystemExit('FAIL: ' + repr((n,umask,b)))
        if not (count == expected): raise SystemExit('FAIL: ' + repr('line 118'))
        # The full family (empty witness) is separate from canonical_families.
        for prod in prods:
            coeff=ranks(n,(1<<(1<<n))-1,prod)
            if not (all(d>=0 for d in ulc_defects(coeff))): raise SystemExit('FAIL: ' + repr('line 122'))
        summary.append({"n":n,"distinct_singleton_pair_families":count,
                        "weight_vectors":weight_vectors,
                        "weighted_rank_checks":3*count,
                        "full_family_checked_separately":True})
    return summary


def all_downsets(n):
    families=[0,1]  # empty family, and {empty set}, on no elements
    for j in range(n):
        shift=1<<j
        families=[lower | (upper<<shift)
                  for lower in families for upper in families
                  if upper & ~lower == 0]
    return families


def verify_marked_lemma(max_m=5):
    result=[]
    for m in range(1,max_m+1):
        full=(1<<m)-1
        all_fam=all_downsets(m)
        admitted=0
        comparisons=0
        for family in all_fam:
            members=[s for s in range(1<<m) if family>>s & 1]
            # For a downset, having a pair with union W is equivalent to
            # containing a complementary pair. Check this direct condition.
            if any((family>>(full^s))&1 for s in members):
                continue
            admitted+=1
            for marked in range(1<<m):
                beta=[0]*(m+1)
                for s in members:
                    if s & marked:
                        beta[s.bit_count()]+=1
                for a in range(m//2+1):
                    b=m-a
                    if not (beta[a]>=beta[b]): raise SystemExit('FAIL: ' + repr((m,family,marked,a,b,beta)))
                    comparisons+=1
        result.append({"m":m,"all_downsets":len(all_fam),
                       "no_covering_pair_downsets":admitted,
                       "marked_rank_comparisons":comparisons})
    return result


def verify_counterexamples():
    triples=[sum(1<<i for i in e) for e in combinations(range(1,5),3)]
    c5=ranks(5,upmask(5,[1]+triples))
    if not (c5 == [0,1,4,10,5,1]): raise SystemExit('FAIL: ' + repr('line 172'))
    if not (ulc_defects(c5)[1] == -24): raise SystemExit('FAIL: ' + repr('line 173'))
    c4=ranks(4,upmask(4,[1,14]),products(4,[1,2,2,2]))
    if not (c4 == [0,1,6,20,8]): raise SystemExit('FAIL: ' + repr('line 175'))
    if not (ulc_defects(c4)[1] == -36): raise SystemExit('FAIL: ' + repr('line 176'))
    uniform=[]
    for M in [1,2,3,10,43,44,100]:
        c6=ranks(6,upmask(6,[7,56]),products(6,[1,M,M,3,3,3]))
        expected=[0,0,0,M*M+27,9*M*M+54*M+27,54*M*M+54*M,27*M*M]
        if not (c6==expected): raise SystemExit('FAIL: ' + repr('line 181'))
        defect=ulc_defects(c6)[3]
        if not (defect == 162*(-M**4+43*M**3+33*M**2+9*M+36)): raise SystemExit('FAIL: ' + repr('line 183'))
        if not ((defect<0)==(M>=44)): raise SystemExit('FAIL: ' + repr('line 184'))
        uniform.append({"M":M,"coefficients":c6,"k4_defect":defect})
    return {"unweighted_width_three":{"n":5,"coefficients":c5,"k2_defect":-24},
            "weighted_width_three":{"n":4,"weights":[1,2,2,2],"coefficients":c4,"k2_defect":-36},
            "weighted_disjoint_triples":uniform}


def main():
    started=time.perf_counter()
    report={"date":"2026-11-04","arithmetic":"exact Python integers; every check is an explicit conditional (active under python -O)",
            "graph_family_scope":"all distinct upsets generated by singleton and pair witnesses on 1..6 labelled elements; three positive integer weight vectors per family",
            "marked_lemma_scope":"all downsets on 1..5 elements, all marked subsets, all complementary ranks",
            "graph_families":verify_graph_families(),
            "marked_downsets":verify_marked_lemma(),
            "counterexamples":verify_counterexamples(),
            "limitations":"Finite verification does not prove a universal theorem or historical novelty."}
    report["elapsed_seconds"]=round(time.perf_counter()-started,3)
    report["status"]="PASS"
    path=Path(__file__).with_name("verification_results.json")
    path.write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps({"status":report["status"],
                      "families":sum(x["distinct_singleton_pair_families"] for x in report["graph_families"]),
                      "weighted_rank_checks":sum(x["weighted_rank_checks"] for x in report["graph_families"]),
                      "marked_comparisons":sum(x["marked_rank_comparisons"] for x in report["marked_downsets"]),
                      "elapsed_seconds":report["elapsed_seconds"]}))


if __name__=="__main__":
    main()
